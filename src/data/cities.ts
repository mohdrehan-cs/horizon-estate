export function getCity(slug: string) {
  return cities.find((city) => city.slug === slug);
}

export function getLocality(citySlug: string, localitySlug: string) {
  return getCity(citySlug)?.localities.find((locality) => locality.slug === localitySlug);
}

export function getCityName(slug: string) {
  return getCity(slug)?.name ?? slug;
}

export function getLocalityName(citySlug: string, localitySlug: string) {
  return (
    getLocality(citySlug, localitySlug)?.name ??
    localitySlug.replace(/-/g, " ").replace(/\b\w/g, (char) => char.toUpperCase())
  );
}

export const allLocalities = cities.flatMap((city) =>
  city.localities.map((locality) => ({ ...locality, cityName: city.name })),
);
