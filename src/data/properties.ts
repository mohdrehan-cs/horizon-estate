export function similarProperties(property: Property, limit = 3) {
  return properties
    .filter(
      (item) =>
        item.id !== property.id &&
        (item.city === property.city || item.type === property.type) &&
        item.listingType === property.listingType,
    )
    .sort((a, b) => {
      const scoreA = (a.city === property.city ? 2 : 0) + (a.type === property.type ? 1 : 0);
      const scoreB = (b.city === property.city ? 2 : 0) + (b.type === property.type ? 1 : 0);
      return scoreB - scoreA;
    })
    .slice(0, limit);
}

